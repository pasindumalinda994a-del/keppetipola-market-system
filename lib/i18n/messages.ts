export function vegetableMatchesQuery(
  name: string,
  query: string,
  t: (key: MessageKey) => string
): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    name.toLowerCase().includes(q) ||
    translateVegetableName(name, t).toLowerCase().includes(q)
  );
}
