export function fillTemplate(
  template: string,
  vars: Record<string, string | number>
): string {
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    template
  );
}

/** English vegetable names from mock data → message keys */
export const vegetableNameKeys: Record<string, MessageKey> = {
  Carrot: "veg.carrot",
  Cabbage: "veg.cabbage",
  Leeks: "veg.leeks",
  Beans: "veg.beans",
  Tomato: "veg.tomato",
  Potato: "veg.potato",
  Beetroot: "veg.beetroot",
  Capsicum: "veg.capsicum",
};

export function translateVegetableName(
  name: string,
  t: (key: MessageKey) => string
): string {
  const key = vegetableNameKeys[name];
  return key ? t(key) : name;
}

export function vegetableMatchesQuery(
  name: string,
  query: string,
  t: (key: MessageKey) => string
): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    name.toLowerCase().includes(q) ||
    translateVegetableName(name, t).toLowerCase().includes(q)
  );
}
